const fs = require('node:fs')
const path = require('node:path')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const lucide = require('lucide-react')

// DFlip's standalone iframe uses the same Lucide shapes as the React UI.
const icons = {
  altnext: 'ChevronRight', altprev: 'ChevronLeft', next: 'ChevronRight', prev: 'ChevronLeft',
  end: 'ChevronsRight', start: 'ChevronsLeft', share: 'Share2', help: 'CircleHelp',
  more: 'Ellipsis', download: 'Download', zoomin: 'ZoomIn', zoomout: 'ZoomOut',
  fullscreen: 'Maximize', fitscreen: 'Expand', thumbnail: 'Grid2X2', outline: 'List',
  close: 'X', search: 'Search', doublepage: 'BookOpen', singlepage: 'FileText',
  sound: 'Volume2', facebook: 'Facebook', google: 'Globe', twitter: 'Twitter',
  mail: 'Mail', play: 'Play', pause: 'Pause',
}
const className = name => `sw-reader-icon-${name.toLowerCase()}`
const configuration = Object.fromEntries(Object.entries(icons).map(([key, name]) => [key, className(name)]))
const css = [
  '/* Generated by scripts/generate-reader-icons.cjs. Do not edit manually. */',
  '[class*="sw-reader-icon-"]::before { content: ""; display: inline-block; width: 1em; height: 1em; vertical-align: -0.125em; background-color: currentColor; -webkit-mask: var(--sw-reader-icon) center / contain no-repeat; mask: var(--sw-reader-icon) center / contain no-repeat; }',
  ...[...new Set(Object.values(icons))].map(name => {
    const svg = renderToStaticMarkup(React.createElement(lucide[name], { size: 24, strokeWidth: 2 }))
    const uri = encodeURIComponent(svg).replace(/'/g, '%27')
    return `.${className(name)} { --sw-reader-icon: url("data:image/svg+xml,${uri}"); }`
  }),
].join('\n') + '\n'
const script = '/* Generated by scripts/generate-reader-icons.cjs. */\n' +
  `window.SW_READER_ICONS = Object.freeze(${JSON.stringify(configuration, null, 2)});\n`
const root = path.join(__dirname, '../public/assets/dflip')
const files = { 'css/lucide-icons.css': css, 'lucide-icons.js': script }
for (const [file, content] of Object.entries(files)) {
  const target = path.join(root, file)
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== content) throw new Error(`Regenerate ${file}: npm run icons:generate`)
  } else fs.writeFileSync(target, content)
}
